import json
from datetime import datetime, timezone
from pathlib import Path
from typing import Literal
from pydantic import BaseModel, Field

from config import EXECUTION_LOG_FILE

FinalStatus = Literal["approved", "max_attempts_exceeded", "technical_error"]
EvaluatorDecision = Literal["approved", "rejected", "evaluation_not_completed"]


class QuestionRunLog(BaseModel):
    class AttemptLog(BaseModel):
        attempt_number: int = Field(..., description="1-based attempt number.")
        candidate_answer: str | None = Field(
            default=None,
            description="Draft answer generated by the Actor (None if Actor call failed).",
        )
        evaluator_decision: EvaluatorDecision = Field(
            ...,
            description=(
                "'approved', 'rejected', or 'evaluation_not_completed' in case of a "
                "technical error."
            ),
        )
        feedback: str = Field(
            ...,
            description="Evaluator feedback or technical error details.",
        )

    scenario_id: str = Field(
        default="interactive",
        description="Identifier for the scenario or chat session.",
    )
    timestamp: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat(),
        description="UTC ISO-8601 timestamp of the run.",
    )
    user_question: str = Field(..., description="The question asked by the user.")
    final_status: FinalStatus | None = Field(
        default=None,
        description="Termination reason: 'approved', 'max_attempts_exceeded', or 'technical_error'.",
    )
    attempts: list[AttemptLog] = Field(
        default_factory=list,
        description="Ordered list of all attempts for this question.",
    )

    def add_attempt(
        self,
        attempt_number: int,
        candidate_answer: str | None,
        evaluator_decision: EvaluatorDecision,
        feedback: str,
    ) -> None:
        self.attempts.append(
            self.AttemptLog(
                attempt_number=attempt_number,
                candidate_answer=candidate_answer,
                evaluator_decision=evaluator_decision,
                feedback=feedback,
            )
        )


class ExecutionLogger:
    def __init__(self, log_file: Path = EXECUTION_LOG_FILE) -> None:
        self.log_file = Path(log_file)

    def log_run(self, run_log: QuestionRunLog) -> None:
        self.log_file.parent.mkdir(parents=True, exist_ok=True)

        existing_entries: list[dict] = []
        if self.log_file.exists():
            raw = self.log_file.read_text(encoding="utf-8").strip()
            if raw:
                try:
                    loaded = json.loads(raw)
                    if isinstance(loaded, list):
                        existing_entries = loaded
                except json.JSONDecodeError:
                    existing_entries = []

        existing_entries.append(run_log.model_dump())
        self.log_file.write_text(
            json.dumps(existing_entries, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )
